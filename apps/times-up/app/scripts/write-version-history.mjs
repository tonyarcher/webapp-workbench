import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(__dirname, '..');
const repoRoot = resolve(appDir, '..', '..', '..');
const outFile = resolve(appDir, 'src', 'generated', 'version-history.ts');

function readPackageVersion() {
    try {
        const pkg = JSON.parse(readFileSync(resolve(appDir, 'package.json'), 'utf8'));
        return typeof pkg.version === 'string' ? pkg.version : '0.0.0';
    } catch {
        return '0.0.0';
    }
}

function git(args) {
    try {
        return execSync(`git ${args}`, { cwd: repoRoot, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
    } catch {
        return '';
    }
}

function cleanSubject(subject) {
    return subject
        .replace(/^(feat|fix|perf|refactor|docs|test|chore|style|build|ci)(\([^)]*\))?!?:\s*/i, '')
        .replace(/\s+/g, ' ')
        .trim();
}

function isUserFacing(subject) {
    return /^(feat|fix|perf)(\(|:|!)/i.test(subject);
}

function squashHistory() {
    // Include the pre-rename paths so the shipped version history survives the move.
    const raw = git(
        'log --pretty=format:%h%x09%ad%x09%s --date=short -60 -- apps/times-up/app apps/times-up/api apps/rss/app apps/rss/api',
    );
    if (!raw) return [];
    const byDate = new Map();
    for (const line of raw.split('\n')) {
        if (!line.trim()) continue;
        const [hash, date, ...rest] = line.split('\t');
        const subject = rest.join('\t').trim();
        if (!hash || !date || !subject) continue;
        if (!isUserFacing(subject)) continue;
        const clean = cleanSubject(subject);
        if (!clean) continue;
        const entry = byDate.get(date) ?? { id: hash, date, items: [], seen: new Set() };
        const key = clean.toLowerCase();
        if (!entry.seen.has(key)) {
            entry.seen.add(key);
            entry.items.push(clean);
        }
        if (!byDate.has(date)) byDate.set(date, entry);
    }
    const history = [];
    for (const entry of byDate.values()) {
        if (entry.items.length === 0) continue;
        // Squash heavily: keep up to 3 highlights per date as one summary.
        const summary = entry.items.slice(0, 3).join(' · ');
        history.push({ id: entry.id, date: entry.date, summary });
        if (history.length >= 12) break;
    }
    return history;
}

function quote(value) {
    return `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r')}'`;
}

function formatHistory(history) {
    if (history.length === 0) return '[]';
    const items = history.map(
        (entry) =>
            `    {\n        id: ${quote(entry.id)},\n        date: ${quote(entry.date)},\n        summary: ${quote(entry.summary)},\n    }`,
    );
    return `[\n${items.join(',\n')},\n]`;
}

const version = readPackageVersion();
const commit = git('rev-parse --short HEAD') || 'unknown';
const buildTime = new Date().toISOString();
const history = squashHistory();

const content = `// Generated by scripts/write-version-history.mjs. Do not edit.
export interface VersionEntry {
    id: string;
    date: string;
    summary: string;
}

export const APP_VERSION = ${quote(version)} as const;
export const APP_COMMIT = ${quote(commit)} as const;
export const BUILD_TIME = ${quote(buildTime)} as const;
export const VERSION_HISTORY: readonly VersionEntry[] = ${formatHistory(history)} as const;
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, content, 'utf8');
console.log(`wrote ${outFile} (${history.length} entries)`);
